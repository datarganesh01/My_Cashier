package com.example.mycashier.Model;

import androidx.room.Entity;
import androidx.room.PrimaryKey;
import androidx.room.ColumnInfo;
import java.io.Serializable;

/**
 * Room entity for transactions.
 */
@Entity(tableName = "transactions")
public class TransactionModel implements Serializable {

    @PrimaryKey(autoGenerate = true)
    private int id;

    @ColumnInfo(name = "type")          // "income" or "expense"
    private String type;

    @ColumnInfo(name = "category")
    private String category;

    @ColumnInfo(name = "note")
    private String note;

    @ColumnInfo(name = "amount")
    private double amount;

    @ColumnInfo(name = "timestamp")
    private long timestamp;

    // Empty constructor required by some serializers / Room (not strictly required)
    public TransactionModel() { }

    // Constructor for inserting new items (id will be autogenerated)
    public TransactionModel(String type, String category, String note, double amount, long timestamp) {
        this.type = type;
        this.category = category;
        this.note = note;
        this.amount = amount;
        this.timestamp = timestamp;
    }

    // Full constructor (useful when reading from DB)
    public TransactionModel(int id, String type, String category, String note, double amount, long timestamp) {
        this.id = id;
        this.type = type;
        this.category = category;
        this.note = note;
        this.amount = amount;
        this.timestamp = timestamp;
    }

    // Getters & Setters
    public int getId() { return id; }
    public void setId(int id) { this.id = id; }

    public String getType() { return type; }
    public void setType(String type) { this.type = type; }

    public String getCategory() { return category; }
    public void setCategory(String category) { this.category = category; }

    public String getNote() { return note; }
    public void setNote(String note) { this.note = note; }

    public double getAmount() { return amount; }
    public void setAmount(double amount) { this.amount = amount; }

    public long getTimestamp() { return timestamp; }
    public void setTimestamp(long timestamp) { this.timestamp = timestamp; }
}
